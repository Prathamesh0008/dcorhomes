const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path');
module.exports = async ({ go, evaluate, call, delay }) => {
  const wait = async expression => { for (let i = 0; i < 150; i++) { if (await evaluate(expression)) return; await delay(100); } throw Error('Timed out: ' + expression); };
  const output = path.resolve('.data/studio-restoration'); fs.mkdirSync(output, { recursive: true });
  const styleGroup = '01 — Choose your style';
  for (const width of process.env.DCORHOME_STUDIO_INTERACTIONS ? [1440] : [390, 768, 1440]) {
    await go('/studio', width);
    await wait(`!!document.querySelector('[data-testid="restored-visualizer"]')`);
    await delay(500);
    const shot = await call('Page.captureScreenshot', { format: 'png', captureBeyondViewport: true });
    fs.writeFileSync(path.join(output, `studio-${width}.png`), Buffer.from(shot.data, 'base64'));
    assert.equal(await evaluate(`document.querySelectorAll('main h1').length`), 1);
    console.log('Restored visualizer', width, 'layout and image loading PASS');
  }
  await evaluate(`window.visualizerPosts=0;const original=window.fetch;window.fetch=(url,options)=>{if(String(url).includes('/api/visualize')&&options?.method==='POST')window.visualizerPosts++;return original(url,options);}`);
  const heading = await evaluate(`document.querySelector('[aria-label="main heading"]').value`);
  await evaluate(`document.querySelector('[aria-label=${JSON.stringify(styleGroup)}] button').click()`);
  await evaluate(`document.querySelector('[aria-label=${JSON.stringify(styleGroup)}] button:nth-child(2)').click()`);
  await wait(`document.querySelector('[data-testid="curtain-config-summary"]').textContent.includes('Classic')`);
  await evaluate(`document.querySelector('[aria-label=${JSON.stringify(styleGroup)}] button').click()`);
  await wait(`new URL(location.href).searchParams.get('style')==='Modern'`);
  await evaluate(`document.querySelector('[aria-label=${JSON.stringify(styleGroup)}] button:nth-child(2)').click()`);
  await wait(`new URL(location.href).searchParams.get('style')==='Classic'`);
  assert.equal(await evaluate(`document.querySelector('[aria-label="main heading"]').value`), heading, 'Aesthetic changed physical heading');
  assert.equal(await evaluate(`new URL(location.href).searchParams.get('style')`), 'Classic');
  await evaluate(`document.querySelector('[aria-label=${JSON.stringify(styleGroup)}] button:nth-child(2)').focus()`);
  await call('Input.dispatchKeyEvent', { type: 'keyDown', key: 'ArrowRight', code: 'ArrowRight' });
  await wait(`document.activeElement.getAttribute('aria-pressed')==='true'`);
  assert.equal(await evaluate(`document.querySelector('[data-testid="curtain-config-summary"]').textContent.includes('Minimalist')`), true);
  const sheer = await evaluate(`JSON.parse(new URL(location.href).searchParams.get('manual')).sheerColor`);
  await wait(`!!document.querySelector('canvas[data-layer="sheer"]')`);
  const before = await evaluate(`({main:document.querySelector('canvas[data-layer="main"]').toDataURL(),sheer:document.querySelector('canvas[data-layer="sheer"]').toDataURL()})`);
  await evaluate(`document.querySelector('[aria-label="main colors"] button[aria-pressed="false"]').click()`);
  await delay(500);
  const after = await evaluate(`({main:document.querySelector('canvas[data-layer="main"]').toDataURL(),sheer:document.querySelector('canvas[data-layer="sheer"]').toDataURL()})`);
  assert.notEqual(before.main, after.main, 'Main preview did not update');
  assert.equal(before.sheer, after.sheer, 'Main color altered sheer preview');
  assert.equal(await evaluate(`JSON.parse(new URL(location.href).searchParams.get('manual')).sheerColor`), sheer);
  const mainBeforeSheer = await evaluate(`document.querySelector('canvas[data-layer="main"]').toDataURL()`);
  await evaluate(`document.querySelector('[aria-label="Enable sheer layer"]').closest('details').open=true;document.querySelector('[aria-label="sheer colors"] button[aria-pressed="false"]').click()`);
  await delay(300);
  assert.equal(await evaluate(`document.querySelector('canvas[data-layer="main"]').toDataURL()`), mainBeforeSheer);
  assert.notEqual(await evaluate(`JSON.parse(new URL(location.href).searchParams.get('manual')).sheerColor`), sheer);
  const mainColor = await evaluate(`JSON.parse(new URL(location.href).searchParams.get('manual')).mainColor`);
  await evaluate(`document.querySelector('[aria-label="Enable sheer layer"]').click()`);
  await wait(`document.querySelector('canvas[data-layer="sheer"]').hidden`);
  await evaluate(`document.querySelector('[aria-label="Enable sheer layer"]').click()`);
  assert.equal(await evaluate(`JSON.parse(new URL(location.href).searchParams.get('manual')).mainColor`), mainColor);
  const enquiry = await evaluate(`document.querySelector('[data-testid="design-enquiry"]').href`);
  assert.ok(new URL(enquiry).searchParams.get('message').includes('Style: Minimalist'));
  const selected = await evaluate(`location.pathname+location.search`);
  assert.equal(await evaluate('window.visualizerPosts'), 0, 'Ordinary selection requested AI');
  await go(selected, 390);
  await wait(`document.querySelector('[data-testid="curtain-config-summary"]').textContent.includes('Minimalist')`);
  const initialScroll = await evaluate(`document.querySelector('[aria-label=${JSON.stringify(styleGroup)}]').scrollLeft`);
  await evaluate(`document.querySelector('[aria-label=${JSON.stringify('Next '+styleGroup+' choices')} ]').click()`);
  await wait(`document.querySelector('[aria-label=${JSON.stringify(styleGroup)}]').scrollLeft>${initialScroll}`);
  assert.equal(await evaluate(`getComputedStyle(document.querySelector('[aria-label=${JSON.stringify(styleGroup)}]')).scrollbarWidth`), 'none');
  await evaluate(`[...document.querySelectorAll('button')].find(b=>b.textContent.includes('Preview My Curtains')).click()`);
  await wait(`!!document.querySelector('input[type="file"]')`);
  assert.equal(await evaluate(`!!document.querySelector('[aria-label="Upload your room photograph"]')`), true);
  assert.equal(await evaluate('window.visualizerPosts || 0'), 0);
  console.log('Styles, keyboard/checkmarks, headings kept separate, independent layers, preview pixels, URL/enquiry transfer, mobile scrolling and explicit upload flow PASS');
};
