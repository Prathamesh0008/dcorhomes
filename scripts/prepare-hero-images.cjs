const fs=require('node:fs'),path=require('node:path'),sharp=require('sharp');
const descriptions=[
 ['A bright living room with full-height sheer curtains, neutral seating and a lake view','Open views · curtain inspiration'],
 ['Soft sheer curtains filtering warm daylight into a bedroom with a neutral bed and bench','Quiet mornings · curtain inspiration'],
 ['Tall arched windows framed by sheer curtains in a light stone interior','Architectural light · curtain inspiration'],
 ['A woman relaxing on a neutral sofa beside floor-to-ceiling sheer curtains','Room to unwind · curtain inspiration'],
 ['A sunlit bedroom with layered curtains and a woman standing beside the window','A softer morning · curtain inspiration'],
 ['Two people beside layered sheer curtains in a bright contemporary living room','Spaces to share · curtain inspiration'],
 ['Sheer curtain layers surrounding a dining table and adjoining living space','Everyday elegance · curtain inspiration'],
 ['Tall arched windows with flowing sheer curtains and views across the city','Light in motion · curtain inspiration'],
 ['An elegant living room with arched windows, sheer curtains and a fireplace','A considered room · curtain inspiration'],
 ['A man seated beside sheer curtains in a bedroom overlooking the city','A moment of calm · curtain inspiration'],
];
(async()=>{
 const source=path.resolve(process.argv[2]||'public/hero'),target=path.resolve('public/images/hero');
 for(let i=1;i<=10;i++)if(!fs.existsSync(path.join(source,`${i}.png`)))throw Error(`Missing supplied image ${i}.png`);
 fs.mkdirSync(target,{recursive:true});
 const slides=[];
 for(let i=1;i<=10;i++){
  const stem=`hero-curtain-${String(i).padStart(2,'0')}`;
  for(const width of [640,1280,1448])await sharp(path.join(source,`${i}.png`)).rotate().resize({width,withoutEnlargement:true}).webp({quality:83,effort:5}).toFile(path.join(target,`${stem}-${width}.webp`));
  slides.push({src:`/images/hero/${stem}-1280.webp`,alt:descriptions[i-1][0],caption:descriptions[i-1][1]});
 }
 fs.writeFileSync('lib/hero-showcase.ts','export type HeroSlide = { src: string; alt: string; caption: string; objectPosition?: string };\n\n// Supplied public/hero/1.png through 10.png, in numeric order.\n// Generated by scripts/prepare-hero-images.cjs; originals remain unchanged.\nexport const heroShowcaseSlides: HeroSlide[] = '+JSON.stringify(slides,null,2)+';\n');
 console.log('Prepared 30 responsive WebP assets from the ten supplied images; originals preserved.');
})().catch(error=>{console.error(error.message);process.exit(1)});
